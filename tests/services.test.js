import { test } from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import User from "../models/User.js";
import Product from "../models/Product.js";
import Cart from "../models/Cart.js";
import web from "../app.js";
import { createUsersApp } from "../services/users/app.js";
import { createProductsApp } from "../services/products/app.js";
import { createStockApp, Inventory } from "../services/stock/app.js";
import { serviceDatabase } from "../services/database-config.js";

test("independent HTTP services and website integration without MongoDB writes", async t => {
  process.env.JWT_SECRET = "test-only-secret";
  process.env.INTERNAL_SERVICE_SECRET = "test-internal-secret";
  const productId = "507f1f77bcf86cd799439011";
  const userId = "507f1f77bcf86cd799439012";
  const products = [{ _id: productId, name: "Silla de prueba", category: "Living", description: "Madera", price: 120, image: "/images/chair.jpg" }];
  const inventory = new Map([[productId, { _id: productId, stock: 3 }]]);
  let failStock = false;
  let failProductDelete = false;
  let user;
  t.mock.method(User, "findOne", async ({ email }) => user?.email === email ? user : null);
  t.mock.method(User, "create", async data => (user = { ...data, _id: userId }));
  t.mock.method(User, "findById", async id => id === userId ? user : null);
  t.mock.method(Product, "find", async () => products);
  t.mock.method(Product, "findById", async id => products.find(product => String(product._id) === String(id)));
  t.mock.method(Product, "create", async data => { products.push(data); return data; });
  t.mock.method(Product, "findByIdAndDelete", async id => {
    if (failProductDelete) throw new Error('Simulated product database outage');
    const index = products.findIndex(product => String(product._id) === String(id));
    return index < 0 ? null : products.splice(index, 1)[0];
  });
  t.mock.method(Inventory, "find", () => ({ lean: async () => [...inventory.values()] }));
  t.mock.method(Inventory, "findById", id => ({ lean: async () => inventory.get(String(id)) }));
  t.mock.method(Inventory, "findOneAndUpdate", async ({ _id }, update) => {
    if (failStock) throw new Error('Simulated inventory database outage');
    if (!inventory.has(String(_id))) inventory.set(String(_id), { _id: String(_id), stock: update.$setOnInsert.stock });
    return inventory.get(String(_id));
  });
  t.mock.method(Inventory, "deleteOne", async ({ _id }) => inventory.delete(String(_id)));
  t.mock.method(Cart, "findOne", () => ({ lean: async () => ({ products: [{ productId, quantity: 2 }] }) }));
  const servers = [];
  const start = async app => {
    const server = app.listen(0, "127.0.0.1");
    servers.push(server);
    await once(server, "listening");
    return `http://127.0.0.1:${server.address().port}`;
  };
  t.after(async () => {
    for (const server of servers) if (server.listening) await new Promise(resolve => server.close(resolve));
  });
  const usersUrl = await start(createUsersApp());
  const productsUrl = await start(createProductsApp());
  process.env.USERS_SERVICE_URL = usersUrl;
  process.env.PRODUCTS_SERVICE_URL = productsUrl;
  const webUrl = await start(web);
  const stockUrl = await start(createStockApp());
  process.env.STOCK_SERVICE_URL = stockUrl;
  const post = (url, body, headers = {}) => fetch(url, { method: "POST", redirect: "manual", headers: { "Content-Type": "application/json", ...headers }, body: JSON.stringify(body) });

  assert.equal((await post(usersUrl + "/users/register", { name: "Ana", email: "ana@example.test", password: "short" })).status, 400);
  let response = await post(webUrl + "/register", { name: "Ana", email: "ana@example.test", password: "Prueba1!" });
  assert.equal(response.status, 302);
  assert.equal(response.headers.get("location"), "/login");
  assert.notEqual(user.password, "Prueba1!");
  assert.equal((await post(usersUrl + "/users/register", { name: "Ana", email: "ana@example.test", password: "Prueba1!" })).status, 409);
  assert.equal((await post(usersUrl + "/users/login", { email: { $ne: null }, password: "x" })).status, 400);
  assert.equal((await post(usersUrl + "/users/login", { email: "ana@example.test", password: "wrong" })).status, 401);
  response = await post(webUrl + "/login", { email: "ana@example.test", password: "Prueba1!" });
  assert.equal(response.status, 200);
  const { token } = await response.json();
  const cookie = response.headers.get("set-cookie").split(";")[0];
  response = await fetch(usersUrl + "/users/me", { headers: { Authorization: `Bearer ${token}` } });
  assert.deepEqual(await response.json(), { id: userId, name: "Ana", email: "ana@example.test" });
  assert.equal((await fetch(usersUrl + "/users/me")).status, 401);
  assert.equal((await fetch(usersUrl + "/users/me", { headers: { Authorization: "Bearer invalid" } })).status, 401);

  assert.deepEqual(await (await fetch(productsUrl + "/products")).json(), products);
  assert.deepEqual(await (await fetch(stockUrl + `/stock/${productId}`)).json(), { productId, stock: 3 });
  assert.deepEqual(await (await fetch(webUrl + "/stock")).json(), [{ productId, stock: 3 }]);
  assert.deepEqual(await (await fetch(webUrl + `/products/${productId}/stock`)).json(), { productId, stock: 3 });
  assert.equal((await fetch(stockUrl + "/stock/invalid")).status, 400);
  assert.equal((await fetch(stockUrl + `/stock/${userId}`)).status, 404);
  assert.equal((await fetch(productsUrl + "/products/invalid")).status, 400);
  assert.equal((await fetch(productsUrl + `/products/${userId}`)).status, 404);
  assert.equal((await post(webUrl + "/products", products[0])).status, 401);
  assert.equal((await post(webUrl + "/products", { ...products[0], stock: -1 }, { Authorization: `Bearer ${token}` })).status, 400);
  response = await post(webUrl + "/products", { ...products[0], stock: 8 }, { Authorization: `Bearer ${token}` });
  assert.equal(response.status, 201);
  const created = (await response.json()).product;
  assert.equal('stock' in created, false);
  assert.equal(inventory.get(created._id).stock, 8);
  const internalPut = (id, stock, key) => fetch(stockUrl + `/internal/stock/${id}`, { method: 'PUT', headers: { 'Content-Type': 'application/json', ...(key ? { 'X-Service-Key': key } : {}) }, body: JSON.stringify({ stock }) });
  assert.equal((await internalPut(created._id, 99)).status, 401);
  assert.equal((await internalPut(created._id, 99, 'wrong-secret')).status, 401);
  assert.equal((await internalPut(created._id, -1, process.env.INTERNAL_SERVICE_SECRET)).status, 400);
  assert.equal((await internalPut(created._id, 99, process.env.INTERNAL_SERVICE_SECRET)).status, 200);
  assert.equal(inventory.get(created._id).stock, 8, 'idempotent initialization never resets quantities');
  failProductDelete = true;
  response = await fetch(productsUrl + `/products/${created._id}`, { method: 'DELETE', headers: { Authorization: `Bearer ${token}` } });
  assert.equal(response.status, 500);
  assert.equal(inventory.get(created._id).stock, 8, 'restore stock if product deletion fails');
  failProductDelete = false;
  response = await fetch(productsUrl + `/products/${created._id}`, { method: 'DELETE', headers: { Authorization: `Bearer ${token}` } });
  assert.equal(response.status, 200);
  assert.equal(inventory.has(created._id), false);
  failStock = true;
  assert.equal((await post(webUrl + "/products", { ...products[0], stock: 2 }, { Authorization: `Bearer ${token}` })).status, 500);
  assert.equal(products.length, 1, 'failed inventory initialization does not create a product');
  failStock = false;
  for (const route of ["/", "/catalog", "/bazar", `/products/${productId}`, "/cart"]) {
    response = await fetch(webUrl + route, { headers: { cookie } });
    assert.equal(response.status, 200, route);
    const html = await response.text();
    if (route === "/" || route === "/catalog") assert.ok(html.includes("gallery-casa-mineral"));
    else assert.ok(html.includes("Silla de prueba"), route);
    if (route === "/cart") assert.ok(html.includes("$240"));
    if (route === `/products/${productId}`) assert.ok(html.includes('In Stock'), 'product detail reads inventory from its service');
  }
  await new Promise(resolve => servers[3].close(resolve));
  response = await fetch(webUrl + `/products/${productId}`);
  assert.equal(response.status, 200);
  assert.ok((await response.text()).includes('No se pudo consultar la disponibilidad'));
  assert.equal((await fetch(webUrl + "/stock")).status, 503);
  await new Promise(resolve => servers[1].close(resolve));
  assert.equal((await fetch(webUrl + "/products")).status, 503);
  assert.equal((await post(webUrl + "/login", { email: "ana@example.test", password: "Prueba1!" })).status, 200);
  await new Promise(resolve => servers[0].close(resolve));
  assert.equal((await post(webUrl + "/login", { email: "ana@example.test", password: "Prueba1!" })).status, 503);
  assert.equal((await fetch(webUrl + "/stock")).status, 503);
});

test('each service selects its own database and inventory collection', () => {
  const env = { MONGO_URI: 'mongodb://localhost/source' };
  assert.equal(serviceDatabase('users', env).dbName, 'noir_usuarios');
  assert.equal(serviceDatabase('products', env).dbName, 'noir_productos');
  assert.equal(serviceDatabase('stock', env).dbName, 'noir_inventario');
  assert.equal(serviceDatabase('stock', { ...env, MONGO_STOCK_URI: 'mongodb://localhost/other', MONGO_STOCK_DB: 'custom' }).uri, 'mongodb://localhost/other');
  assert.equal(Inventory.collection.name, 'inventory');
  assert.equal(Product.schema.path('stock'), undefined);
  const emailIndex = User.schema.indexes().find(([fields]) => fields.email === 1);
  assert.equal(emailIndex[1].unique, true);
  assert.deepEqual(emailIndex[1].partialFilterExpression, { email: { $type: 'string' } });
});
